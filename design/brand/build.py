# --- The boot splash inlined in index.html ---------------------------------

def boot():
    """
    Both index.html files draw the mark before any script has loaded. The SVG
    between the brand:mark markers is replaced here so it never drifts from the
    TypeScript copy.
    """
    dots = "".join(f'<circle cx="{num(x)}" cy="{num(y)}" r="{num(DOT_R)}" opacity="0"/>' for x, y in DOTS)
    svg = (f'<svg class="mark" viewBox="0 0 256 256" aria-hidden="true">'
           f'<path class="stem" d="{STEM}"/><path class="tail" d="{TAIL}"/><path class="bowl" d="{BOWL}"/>'
           f'<g class="dots">{dots}</g></svg>')
    for rel in ("apps/desktop/index.html", "apps/web/index.html"):
        path = os.path.join(ROOT, rel)
        with open(path) as f:
            text = f.read()
        new, n = re.subn(r"(<!-- brand:mark -->).*?(<!-- /brand:mark -->)",
                         lambda m: m.group(1) + svg + m.group(2), text, flags=re.S)
        if n != 1:
            sys.exit(f"{rel}: expected one <!-- brand:mark --> block, found {n}")
        if new != text:
            write(rel, new)


# --- PNG and ICO -----------------------------------------------------------

def chrome():
    for name in ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser"):
        if shutil.which(name):
            return shutil.which(name)
    mac = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
    return mac if os.path.exists(mac) else None


def render(svg_text, size, out_rel, tmp, round_mask=False):
    browser = chrome()
    if not browser:
        sys.exit("--png needs Chrome or Chromium on PATH")
    clip = "border-radius:50%;overflow:hidden;" if round_mask else ""
    html = os.path.join(tmp, "page.html")
    with open(html, "w") as f:
        f.write(f'<!doctype html><html><body style="margin:0;background:transparent">'
                f'<div style="width:{size}px;height:{size}px;{clip}">'
                f'{svg_text.replace("<svg ", f"<svg width={size} height={size} ", 1)}</div></body></html>')
    out = out_rel if os.path.isabs(out_rel) else os.path.join(ROOT, out_rel)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run([browser, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    "--force-device-scale-factor=1", "--default-background-color=00000000",
                    f"--window-size={size},{size}", f"--screenshot={out}", f"file://{html}"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not os.path.isabs(out_rel):
        print("wrote", out_rel)


def ico(png_rels, out_rel):
    """An ICO is a directory of PNGs; every Windows since Vista reads them as is."""
    blobs = []
    for rel in png_rels:
        with open(rel, "rb") as f:
            blobs.append(f.read())
    head = struct.pack("<HHH", 0, 1, len(blobs))
    offset = 6 + 16 * len(blobs)
    entries = b""
    for blob in blobs:
        w, h = struct.unpack(">II", blob[16:24])
        entries += struct.pack("<BBBBHHII", w % 256, h % 256, 0, 0, 1, 32, len(blob), offset)
        offset += len(blob)
    with open(os.path.join(ROOT, out_rel), "wb") as f:
        f.write(head + entries + b"".join(blobs))
    print("wrote", out_rel)


def pngs():
    tile, small, square = svg_tile(), svg_tile(small=True), svg_tile(square=True)
    with tempfile.TemporaryDirectory() as tmp:
        # Window, taskbar and installer icon; electron-builder makes .ico/.icns from it.
        render(tile, 512, "apps/desktop/public/icon.png", tmp)
        render(small, 64, "apps/desktop/public/tray.png", tmp)
        render(tile, 512, "docs/static/img/icon.png", tmp)
        render(square, 180, "apps/desktop/public/apple-touch-icon.png", tmp)
        for size in (16, 32, 48):
            render(small if size < 48 else tile, size, os.path.join(tmp, f"favicon-{size}.png"), tmp)
        ico([os.path.join(tmp, f"favicon-{s}.png") for s in (16, 32, 48)], "docs/static/img/favicon.ico")
        # Launchers older than Android 8 have no adaptive icon and take these as they are.
        res = "apps/android/app/src/main/res"
        for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
            render(tile, size, f"{res}/mipmap-{density}/ic_launcher.png", tmp)
            render(square, size, f"{res}/mipmap-{density}/ic_launcher_round.png", tmp, round_mask=True)


