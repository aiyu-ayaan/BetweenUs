#!/usr/bin/env python3
"""
Builds every copy of the BetweenUs mark from one drawing.

The mark is a lowercase b whose bowl is a speech bubble: the stem runs down
into the bubble's tail. It is drawn here, once, as three parts - the stem, the
bowl (a ring) and the tail - so the clients can animate it: the bubble pops,
the stem rises out of it, the tail flicks out, and while something is being
waited for three typing dots play in the bowl. Everything else - the favicon,
the PWA and desktop icons, the Android launcher, splash, notification and
in-app drawables, the TypeScript and Kotlin path constants, the boot splash
inlined in both index.html files, the docs images - is written by this script.
Edit the geometry below and run it again; do not edit the outputs by hand.

    python3 design/brand/build.py           # SVG, XML, TS, Kotlin, HTML
    python3 design/brand/build.py --png     # also the PNG and ICO files (needs Chrome)

See development/devdocs/BRAND.md.
"""

import math
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HERE = os.path.dirname(os.path.abspath(__file__))

# The dark theme's --color-accent and --color-ground (apps/desktop/src/index.css).
ACCENT = "#7C5CFF"
GROUND = "#06070A"

HEADER = "Generated by design/brand/build.py - do not edit by hand."


def num(v, places=2):
    s = f"{v:.{places}f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


# --- The drawing -------------------------------------------------------------
#
# On a 256 box. The stem is as wide as the ring, so the letter has one weight.
# The tail carries the stem's left edge on at 75 degrees to a point, then comes
# back up at 15 degrees until it meets the bowl - which also fills the notch
# where a b's stem would otherwise meet its bowl. The whole footprint is centred
# on x and sits a little above the middle, where a mark looks centred.

BOWL_C = (144.0, 148.0)  # the bubble's centre: where it pops from, where the dots sit
STEM_FOOT_Y = 218.0      # the stem rises from here (the bowl's bottom)
TAIL_ROOT = (92.0, 190.0)  # the tail flicks out from here, where it meets stem and bowl
DOT_R = 6.0              # the typing dots, inside the counter
DOT_GAP = 15.0


def parts(stem_l, stem_w, top, r, counter, tip_y=232.0, steep=75, shallow=15):
    cx, cy = BOWL_C
    rc = stem_w / 2
    sx = stem_l + stem_w
    cap = top + rc
    stem = f"M{num(stem_l)} {num(cap)}A{num(rc)} {num(rc)} 0 0 1 {num(sx)} {num(cap)}V{num(cy + r)}H{num(stem_l)}Z"
    # Outer circle one way, counter the other: a ring under either fill rule.
    bowl = (f"M{num(cx - r)} {num(cy)}A{num(r)} {num(r)} 0 0 1 {num(cx + r)} {num(cy)}"
            f"A{num(r)} {num(r)} 0 0 1 {num(cx - r)} {num(cy)}Z"
            f"M{num(cx - counter)} {num(cy)}A{num(counter)} {num(counter)} 0 0 0 {num(cx + counter)} {num(cy)}"
            f"A{num(counter)} {num(counter)} 0 0 0 {num(cx - counter)} {num(cy)}Z")
    start_y = tip_y - 50
    tip_x = stem_l - (tip_y - start_y) / math.tan(math.radians(steep))
    k = math.tan(math.radians(shallow))

    def above(x):  # the 15-degree edge, less the bowl's lower half, at x
        return (tip_y - k * (x - tip_x)) - (cy + math.sqrt(max(r * r - (x - cx) ** 2, 0)))

    lo, hi = tip_x, cx
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if above(mid) > 0 else (lo, mid)
    px, py = lo, tip_y - k * (lo - tip_x)
    # Run on a little into the ring so the seam is buried under the bowl.
    a = math.atan2(py - cy, px - cx) - 0.25
    ring = (r + counter) / 2
    qx, qy = cx + ring * math.cos(a), cy + ring * math.sin(a)
    tail = (f"M{num(stem_l)} {num(start_y)}L{num(tip_x)} {num(tip_y)}L{num(px)} {num(py)}"
            f"L{num(qx)} {num(qy)}L{num(sx)} {num(start_y)}Z")
    return stem, bowl, tail


STEM, BOWL, TAIL = parts(stem_l=54, stem_w=38, top=23, r=70, counter=32)
# For 24px and under: a heavier stem and ring and a smaller counter, which would
# otherwise close up to a speck.
STEM_SMALL, BOWL_SMALL, TAIL_SMALL = parts(stem_l=51, stem_w=44, top=23, r=72, counter=28)

DOTS = [(BOWL_C[0] + i * DOT_GAP, BOWL_C[1]) for i in (-1, 0, 1)]

# The mark's size on the app-icon tile.
TILE_SCALE = 0.68


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


def drawing(small=False):
    return (STEM_SMALL, BOWL_SMALL, TAIL_SMALL) if small else (STEM, BOWL, TAIL)


# --- SVG -------------------------------------------------------------------

def svg_paths(small=False):
    return "".join(f'<path d="{d}"/>' for d in drawing(small))


def svg_mark(fill, small=False):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>BetweenUs</title>'
            f'<g fill="{fill}">{svg_paths(small)}</g></svg>\n')


def svg_tile(small=False, square=False):
    """The app icon: the mark in white on an accent tile."""
    scale = TILE_SCALE + (0.04 if small else 0)
    shape = '<rect width="256" height="256" fill="{a}"/>' if square else '<rect width="256" height="256" rx="58" fill="{a}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>BetweenUs</title>'
            + shape.format(a=ACCENT)
            + f'<g fill="#fff" transform="translate(128 128) scale({num(scale)}) translate(-128 -128)">'
            f'{svg_paths(small)}</g></svg>\n')


def svgs():
    write("design/brand/logo.svg", svg_mark("#000"))
    write("design/brand/logo-reversed.svg", svg_mark("#fff"))
    write("design/brand/logo-accent.svg", svg_mark(ACCENT))
    write("design/brand/logo-small.svg", svg_mark("#000", small=True))
    write("design/brand/app-icon.svg", svg_tile())
    write("design/brand/app-icon-square.svg", svg_tile(square=True))
    write("design/brand/favicon.svg", svg_tile(small=True))
    # The browser tab icon; it is 16px most of the time, hence the small cut.
    write("apps/desktop/public/icon.svg", svg_tile(small=True))
    write("apps/admin/public/icon.svg", svg_tile(small=True))
    write("icon.svg", svg_tile())
    write("docs/static/img/icon.svg", svg_tile(small=True))
    write("docs/static/img/logo.svg", svg_mark(ACCENT))


# --- TypeScript and Kotlin -------------------------------------------------

def code():
    for rel in ("apps/desktop/src/components/brand-mark.ts", "apps/admin/src/brand-mark.ts"):
        write(rel, ts())
    write("apps/android/ui-common/src/main/java/com/aatech/betweenus/ui/components/BrandMarkPaths.kt", kotlin())


