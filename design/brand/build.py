# --- Android ---------------------------------------------------------------

def vector(paths, size_dp, viewport, group="", comment=""):
    pad = "        " if group else "    "
    body = "".join(
        f'\n{pad}<path\n{pad}    android:fillColor="{color}"\n{pad}    android:pathData="{d}" />'
        for d, color in paths)
    if group:
        body = f"\n    <group{group}>{body}\n    </group>"
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER}{comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">{body}
</vector>
"""


def fit(box_dp, canvas=108):
    """A group that puts the 256 box at `box_dp` in the middle of the canvas."""
    s = box_dp / 256
    t = canvas / 2 - 128 * s
    return f'\n        android:scaleX="{num(s, 4)}"\n        android:scaleY="{num(s, 4)}"\n        android:translateX="{num(t, 4)}"\n        android:translateY="{num(t, 4)}"'


def splash():
    """
    The Android 12+ splash: the bubble pops, the stem rises out of it and the
    tail flicks out. 860ms, inside the platform's 1000ms cap; the first 200ms
    sit out the launch transition, which would otherwise hide the pop.
    """
    # The 256 box at the same scale as the old mark's, which was measured on a
    # recorded launch to come out at the 88dp box the Compose LoadingScreen
    # draws the mark in, so the hand-over from one to the other does not jump.
    s = 0.125
    t = 54 - 128 * s
    bx, by = BOWL_C
    tx, ty = TAIL_ROOT

    def anim(name, prop, start, duration, frm, to, curve):
        # One animator per target, platform interpolators only. The splash is
        # played by the system's renderer, and a nested set or an inline
        # interpolator there left the mark invisible or skipped to the end -
        # hence a group per axis rather than one animator on both.
        return f"""
    <target android:name="{name}">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="{duration}"
                android:interpolator="@android:interpolator/{curve}"
                android:propertyName="{prop}"
                android:startOffset="{start}"
                android:valueFrom="{frm}"
                android:valueTo="{to}"
                android:valueType="floatType" />
        </aapt:attr>
    </target>"""

    def path(name, d, alpha="1"):
        return f"""
                        <path
                            android:name="{name}"
                            android:fillAlpha="{alpha}"
                            android:fillColor="@color/splash_mark"
                            android:pathData="{d}" />"""

    targets = (
        anim("bowl_x", "scaleX", 200, 450, "0.3", "1", "overshoot")
        + anim("bowl_y", "scaleY", 200, 450, "0.3", "1", "overshoot")
        + anim("bowl", "fillAlpha", 200, 150, "0", "1", "linear")
        + anim("stem", "scaleY", 330, 380, "0", "1", "fast_out_slow_in")
        + anim("tail_x", "scaleX", 540, 320, "0", "1", "overshoot")
        + anim("tail_y", "scaleY", 540, 320, "0", "1", "overshoot")
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER}
     Splash animation: the bubble pops, the stem rises out of it, the tail
     flicks out. 860ms in all; keep windowSplashScreenAnimationDuration and
     SPLASH_MS in MainActivity in step. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector
            android:width="108dp"
            android:height="108dp"
            android:viewportWidth="108"
            android:viewportHeight="108">
            <group
                android:scaleX="{num(s, 4)}"
                android:scaleY="{num(s, 4)}"
                android:translateX="{num(t, 4)}"
                android:translateY="{num(t, 4)}">
                <group
                    android:name="stem"
                    android:pivotY="{num(STEM_FOOT_Y)}"
                    android:scaleY="0">{path("stem_path", STEM)}
                </group>
                <group
                    android:name="tail_x"
                    android:pivotX="{num(tx)}"
                    android:pivotY="{num(ty)}"
                    android:scaleX="0">
                    <group
                        android:name="tail_y"
                        android:pivotX="{num(tx)}"
                        android:pivotY="{num(ty)}"
                        android:scaleY="0">{path("tail_path", TAIL)}
                    </group>
                </group>
                <group
                    android:name="bowl_x"
                    android:pivotX="{num(bx)}"
                    android:pivotY="{num(by)}"
                    android:scaleX="0.3">
                    <group
                        android:name="bowl_y"
                        android:pivotX="{num(bx)}"
                        android:pivotY="{num(by)}"
                        android:scaleY="0.3">{path("bowl", BOWL, "0")}
                    </group>
                </group>
            </group>
        </vector>
    </aapt:attr>{targets}
</animated-vector>
"""


