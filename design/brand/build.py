#!/usr/bin/env python3
"""
Builds every copy of the BetweenUs mark from one drawing.

The mark is two profiles facing each other inside a disc; the light shape
between them is what the two of them share. It is drawn here, once, as two
halves (left face, right face) so the clients can animate the faces leaning in.
Everything else - the favicon, the PWA and desktop icons, the Android launcher,
splash, notification and in-app drawables, the TypeScript and Kotlin path
constants, the boot splash inlined in both index.html files, the docs images -
is written by this script. Edit the profile below and run it again; do not edit
the outputs by hand.

    python3 design/brand/build.py           # SVG, XML, TS, Kotlin, HTML
    python3 design/brand/build.py --png     # also the PNG and ICO files (needs Chrome)

See development/devdocs/BRAND.md.
"""

import math
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HERE = os.path.dirname(os.path.abspath(__file__))

# The dark theme's --color-accent and --color-ground (apps/desktop/src/index.css).
ACCENT = "#7C5CFF"
GROUND = "#06070A"

# The drawing lives on a 256 box: a disc of radius 104 about the centre, split
# by a vertical gap whose two edges are the profiles.
C = 128.0
R = 104.0

# Half the width of the gap at each height, top to bottom: forehead, brow,
# nose, under the nose, upper lip, mouth, lower lip, chin, neck. The first and
# last heights are taken from where that width meets the disc.
PROFILE = [(22, 0), (21, 58), (19, 84), (7, 104), (6, 111), (17, 123), (11, 138),
           (16, 149), (11, 160), (13, 172), (24, 198), (30, 0)]

# The same idea with only a nose and a chin, for 24px and under: the favicon,
# the tray, the status bar. The full profile's lips close up below that size.
PROFILE_SMALL = [(24, 0), (22, 70), (10, 106), (12, 114), (22, 130), (14, 168), (30, 0)]

# How far apart the halves start in the intro, in 256-box units each side.
INTRO_SPREAD = 36

HEADER = "Generated by design/brand/build.py - do not edit by hand."


def num(v, places=2):
    s = f"{v:.{places}f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def through(points):
    """A Catmull-Rom spline through the points, as cubic segments."""
    d = ""
    for i in range(len(points) - 1):
        p0 = points[max(i - 1, 0)]
        p1 = points[i]
        p2 = points[i + 1]
        p3 = points[min(i + 2, len(points) - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{num(c1[0])} {num(c1[1])} {num(c2[0])} {num(c2[1])} {num(p2[0])} {num(p2[1])}"
    return d


def halves(profile):
    profile = list(profile)
    top, bottom = profile[0][0], profile[-1][0]
    profile[0] = (top, C - math.sqrt(R * R - top * top))
    profile[-1] = (bottom, C + math.sqrt(R * R - bottom * bottom))
    left = [(C - w, y) for w, y in profile]
    right = [(C + w, y) for w, y in profile]
    l0, r0 = left[0], right[0]
    return (
        f"M{num(l0[0])} {num(l0[1])}{through(left)}A{num(R)} {num(R)} 0 0 1 {num(l0[0])} {num(l0[1])}Z",
        f"M{num(r0[0])} {num(r0[1])}{through(right)}A{num(R)} {num(R)} 0 0 0 {num(r0[0])} {num(r0[1])}Z",
    )


LEFT, RIGHT = halves(PROFILE)
LEFT_SMALL, RIGHT_SMALL = halves(PROFILE_SMALL)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


# --- SVG -------------------------------------------------------------------

def svg_mark(fill, small=False):
    l, r = (LEFT_SMALL, RIGHT_SMALL) if small else (LEFT, RIGHT)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>BetweenUs</title>'
            f'<g fill="{fill}"><path d="{l}"/><path d="{r}"/></g></svg>\n')


def svg_tile(small=False, square=False):
    """The app icon: the mark in white on an accent tile."""
    l, r = (LEFT_SMALL, RIGHT_SMALL) if small else (LEFT, RIGHT)
    scale = 0.74 if small else 0.7
    shape = '<rect width="256" height="256" fill="{a}"/>' if square else '<rect width="256" height="256" rx="58" fill="{a}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>BetweenUs</title>'
            + shape.format(a=ACCENT)
            + f'<g fill="#fff" transform="translate(128 128) scale({scale}) translate(-128 -128)">'
            f'<path d="{l}"/><path d="{r}"/></g></svg>\n')


def svgs():
    write("design/brand/logo.svg", svg_mark("#000"))
    write("design/brand/logo-reversed.svg", svg_mark("#fff"))
    write("design/brand/logo-accent.svg", svg_mark(ACCENT))
    write("design/brand/logo-small.svg", svg_mark("#000", small=True))
    write("design/brand/app-icon.svg", svg_tile())
    write("design/brand/app-icon-square.svg", svg_tile(square=True))
    write("design/brand/favicon.svg", svg_tile(small=True))
    # The browser tab icon; it is 16px most of the time, hence the small cut.
    write("apps/desktop/public/icon.svg", svg_tile(small=True))
    write("apps/admin/public/icon.svg", svg_tile(small=True))
    write("icon.svg", svg_tile())
    write("docs/static/img/icon.svg", svg_tile(small=True))
    write("docs/static/img/logo.svg", svg_mark(ACCENT))


# --- TypeScript and Kotlin -------------------------------------------------

def code():
    for rel in ("apps/desktop/src/components/brand-mark.ts", "apps/admin/src/brand-mark.ts"):
        write(rel, ts())
    write("apps/android/ui-common/src/main/java/com/aatech/betweenus/ui/components/BrandMarkPaths.kt", kotlin())


